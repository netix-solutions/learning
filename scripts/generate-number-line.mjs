import {writeFileSync} from 'node:fs';
import {numberLineQuestions} from './number-line-content.mjs';
import {mathProgressionSQL} from './generate-math-progression.mjs';
const rows=numberLineQuestions();
const sql=mathProgressionSQL(rows).replace(/-- GENERATED[\s\S]*?with incoming/,`-- Generated by scripts/generate-number-line.mjs from original authored problems.
-- Additive content: preserve every existing question and learner attempt.
with incoming`);
writeFileSync('supabase/seeds/number-line.sql',sql);
const path=process.argv[2];
if(path){
 if(!/^supabase\/migrations\/\d+_number_line_rescue\.sql$/.test(path))throw new Error('Use a CLI-generated number_line_rescue migration path');
 writeFileSync(path,`-- The existing generic scorer compares [direction, amount] as JSON, so no RPC or privileges change.
alter table public.questions drop constraint questions_kind_check;
alter table public.questions add constraint questions_kind_check check(kind in ('mcq','truefalse','match','order','categorize','tapword','numberline'));
\n${sql}`);
}
console.log(`Generated ${rows.length} number-line questions for grades 1 and 2.`);
